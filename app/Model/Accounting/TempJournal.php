<?php

namespace App\Model\Accounting;

use App\LogDelete;
use Carbon\Carbon;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\DB;

class TempJournal extends Model
{
    protected $table = 'temp_journals';

    protected $fillable = [
        'jubilant_id',
        'coa_id',
        'trans_date',
        'bank_date',
        'debit',
        'credit',
        'invoice_number',
        'information',
        'approved',
        'd_or_c',
        'pair',
        'club_id',
    ];

    // belongsTo
    public function tempjournal_jubilant() {
        return $this->belongsTo('App\Model\Jubilant\Jubilant', 'jubilant_id');
    }

    public function tempjournal_coa() {
        return $this->belongsTo('App\Model\Accounting\ChartOfAccount', 'coa_id');
    }

    public function tempjournal_club() {
        return $this->belongsTo('App\Mode\Club\ClubInfo', 'club_id');
    }

    // Trigger
    public static function boot()
    {
        parent::boot(); // TODO: Change the autogenerated stub

        self::deleted(function($model){
            $log = new LogDelete();
            $log->user_id = Auth::user()->id;
            $log->information = 'table_temp_journals '.$model;
            $log->save();
        });
    }
}
