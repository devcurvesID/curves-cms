<?php

namespace App\Model\Product;

use App\LogDelete;
use Carbon\Carbon;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\DB;

class ProductPaymentDetail extends Model
{
    protected $table = 'product_payment_details';

    protected $fillable = [
        'product_payment_id',
        'product_id',
        'price',
        'qty',
        'discount_percent',
        'discount_value',
    ];

    public function productpaymentdetail_productrefunddetail() {
        return $this->hasMany('App\Model\Product\ProductRefundDetail', 'product_payment_detail_id');
    }

    public function productpaymentdetail_productpayment() {
        return $this->belongsTo('App\Model\Product\ProductPayment', 'product_payment_id');
    }

    public function productpaymentdetail_product() {
        return $this->belongsTo('App\Model\Product\Product', 'product_id');
    }

    // Trigger
    public static function boot()
    {
        parent::boot(); // TODO: Change the autogenerated stub

        self::deleted(function($model){
            $log = new LogDelete();
            $log->user_id = Auth::user()->id;
            $log->information = 'table_product_payment_details '.$model;
            $log->save();
        });
    }
}
