<?php

namespace App\Model\Product;

use App\LogDelete;
use Carbon\Carbon;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\DB;

class ProductPayment extends Model
{
    protected $table = 'product_payments';

    protected $fillable = [
        'club_id',
        'cashier_id',
        'payment_method_id',
        'payment_number',
        'subtotal',
        'tax_type_id',
        'tax_value',
        'voucher_code',
        'voucher_value',
        'total',
        'pay',
        'change',
        'payment_date',
        'member_id',
        'bank_id',
        'invoice_discount',
        'is_reward',
        'is_billed',
    ];

    public function getPrettyProductPaymentAttribute(){
        return $this->payment_number .' ('.Carbon::parse($this->payment_date)->format('d-m-Y').')';
    }

    public function productpayment_productpaymentdetail() {
        return $this->hasMany('App\Model\Product\ProductPaymentDetail', 'product_payment_id');
    }

    public function productpayment_productrefund() {
        return $this->hasMany('App\Model\Product\ProductRefund', 'product_refund_id');
    }

    public function productpayment_cobilldetail() {
        return $this->hasMany('App\Model\HQ\ConsignmentOrderBillDetail', 'product_payment_id');
    }

    public function productpayment_club() {
        return $this->belongsTo('App\Model\Club\ClubInfo', 'club_id');
    }

    public function productpayment_cashier() {
        return $this->belongsTo('App\User', 'cashier_id');
    }

    public function productpayment_paymentmethod() {
        return $this->belongsTo('App\Model\MasterData\PaymentMethod', 'payment_method_id');
    }

    public function productpayment_taxtype() {
        return $this->belongsTo('App\Model\Tax\Taxtype', 'tax_type_id');
    }

    public function productpayment_user() {
        return $this->belongsTo('App\User', 'member_id');
    }

    public function productpayment_bank(){
        return $this->belongsTo('App\Model\MasterData\Bank', 'bank_id');
    }

    // Trigger
    public static function boot()
    {
        parent::boot(); // TODO: Change the autogenerated stub

        self::deleted(function($model){
            $log = new LogDelete();
            $log->user_id = Auth::user()->id;
            $log->information = 'table_product_payments '.$model;
            $log->save();
        });
    }
}
